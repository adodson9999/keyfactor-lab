@pytest.mark.parametrize("device", MOBILE_DEVICES, ids=[d["name"] for d in MOBILE_DEVICES])
def test_mobile_page_loads(device):
    """
    TEST 4: Verify the certificate-secured page loads on each mobile device.

    Opens the local HTTPS server in a Chromium browser configured to emulate
    a real mobile device (iPhone, Android, iPad). Checks that the page loads
    without errors and the expected content is present.

    ignore_https_errors=True is used here because our cert is self-signed
    and not trusted by the OS. In a real environment with a CA-issued cert,
    this would be False — the cert would be trusted natively.
    This mirrors how Keyfactor's product eliminates the need for self-signed
    certs by providing properly trusted enterprise certificates.

    @pytest.mark.parametrize runs this test once for each device in MOBILE_DEVICES
    """
    with sync_playwright() as p:
        # Launch a headless Chromium browser (no visible window)
        # headless=True is required for CI/CD pipelines
        browser = p.chromium.launch(headless=True)

        # Create a browser context configured to emulate this specific mobile device
        # This sets screen size, user agent, touch support, and pixel density
        context = browser.new_context(
            user_agent=device["user_agent"],
            viewport=device["viewport"],
            device_scale_factor=device["device_scale_factor"],
            is_mobile=device["is_mobile"],
            has_touch=device["has_touch"],
            ignore_https_errors=True,   # required for self-signed certs
        )

        # Open a new browser tab
        page = context.new_page()

        # Navigate to our local HTTPS server
        response = page.goto(SERVER_URL, timeout=10000)

        # Verify the server returned a successful HTTP status code (200 = OK)
        assert response.status == 200, \
            f"FAIL: {device['name']} got HTTP {response.status} — expected 200"

        # Verify the page content contains our expected marker text
        # This confirms the full page loaded, not just the HTTP headers
        content = page.content()
        assert "CERT_OK" in content, \
            f"FAIL: {device['name']} — expected content not found in page"

        print(f"  {device['name']}: page loaded ✓")

        # Close the browser context and browser to free memory
        context.close()
        browser.close()


@pytest.mark.parametrize("device", MOBILE_DEVICES, ids=[d["name"] for d in MOBILE_DEVICES])
def test_mobile_user_agent(device):
    """
    TEST 5: Verify each device is presenting the correct mobile user agent.

    This confirms the browser context is properly configured as a mobile device.
    In enterprise PKI testing, user agent verification matters because some
    certificate policies are enforced differently based on client type.
    """
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)

        # Create context with the device's user agent
        context = browser.new_context(
            user_agent=device["user_agent"],
            viewport=device["viewport"],
            is_mobile=device["is_mobile"],
            ignore_https_errors=True,
        )

        page = context.new_page()
        page.goto(SERVER_URL, timeout=10000)

        # Use JavaScript to read the browser's actual user agent string
        # This confirms Playwright correctly applied the mobile device profile
        actual_ua = page.evaluate("() => navigator.userAgent")

        # Verify the user agent contains expected mobile keywords
        assert device["user_agent"].split()[0] in actual_ua, \
            f"FAIL: {device['name']} user agent mismatch"

        print(f"  {device['name']}: user agent verified ✓")

        context.close()
        browser.close()