def test_cert_not_expired():
    """TEST 1: Certificate has not expired."""
    cert = load_cert(CERT_FILE)
    assert cert.not_valid_after_utc > datetime.now(timezone.utc), \
        "FAIL: Certificate is expired!"


def test_cert_key_size():
    """TEST 2: Certificate key is at least 2048 bits."""
    cert = load_cert(CERT_FILE)
    key_size = cert.public_key().key_size
    assert key_size >= MIN_KEY_SIZE, \
        f"FAIL: Key size {key_size} bits is below minimum {MIN_KEY_SIZE}"


def test_cert_expiry_warning():
    """TEST 3: Certificate has more than 30 days remaining."""
    cert = load_cert(CERT_FILE)
    days_remaining = (cert.not_valid_after_utc - datetime.now(timezone.utc)).days
    assert days_remaining > EXPIRY_WARNING_DAYS, \
        f"FAIL: Cert expiring in {days_remaining} days!"


